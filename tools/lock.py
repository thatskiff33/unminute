# tools/lock.py
# Hash-locked dependencies (#111 B1). requirements.in lists Unminute's direct
# runtime dependencies; requirements.txt is generated from it and pins every
# package, for Windows x64 and CPython 3.12, wheels only, with its SHA-256
# hashes. The CI tool locks in requirements/ are generated the same way.
#
#   python tools/lock.py                       regenerate every lock
#   python tools/lock.py --check               fail if a lock is out of date (CI)
#   python tools/lock.py --upgrade-package X   move X to the newest version allowed
#   python tools/lock.py --subset numpy av     print the hashed lines for these
#                                              packages and all their dependencies
#
# A lock keeps its versions unless its .in file needs a change, so a re-lock
# changes only what was asked for. Only versions public for COOLDOWN_DAYS are
# chosen: the cut-off date is written into each lock, and --check reuses it.
# Needs uv at the version pinned in requirements/ci-lock.in
# (pip install --require-hashes -r requirements/ci-lock.txt) and the network.

import argparse
import datetime
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

COOLDOWN_DAYS = 7

ROOT = Path(__file__).resolve().parents[1]

WINDOWS = ["--python-platform", "x86_64-pc-windows-msvc", "--python-version", "3.12",
           "--only-binary", ":all:", "--find-links", "packaging/wheels"]
ANY_PLATFORM = ["--universal", "--python-version", "3.12", "--only-binary", ":all:"]

# (input, lock, uv target options, what the lock is for)
LOCKS = [
    ("requirements.in", "requirements.txt", WINDOWS,
     "Unminute's runtime: Windows x64, CPython 3.12, wheels only. The package build\n"
     "# installs it with pip install --require-hashes --no-deps --only-binary=:all:\n"
     "# --find-links packaging/wheels -r requirements.txt"),
    ("requirements/ci-lock.in", "requirements/ci-lock.txt", ANY_PLATFORM,
     "uv for tools/lock.py (CI and local)"),
    ("requirements/ci-audit.in", "requirements/ci-audit.txt", ANY_PLATFORM,
     "pip-audit for tools/audit.py (CI)"),
]
COMMON = ["--generate-hashes", "--no-header", "--annotation-style", "line", "--no-config",
          "--index-url", "https://pypi.org/simple", "--quiet"]


def norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def header(source, purpose, cutoff):
    return (f"# Generated by tools/lock.py from {source}. Do not edit: change {source},\n"
            f"# run python tools/lock.py and commit both.\n# {purpose}\n"
            f"# Only versions published before {cutoff} (a {COOLDOWN_DAYS}-day cooldown).\n")


def recorded_cutoff(text):
    m = re.search(r"^# Only versions published before (\d{4}-\d{2}-\d{2})", text, re.M)
    return m.group(1) if m else None


def body(text):
    """The lock without its header comment."""
    lines = text.replace("\r\n", "\n").split("\n")
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    return "\n".join(lines).strip() + "\n"


def pinned_uv():
    text = (ROOT / "requirements" / "ci-lock.in").read_text(encoding="utf-8")
    return re.search(r"^uv==(\S+)", text, re.M).group(1)


def uv_command():
    """uv from this Python, refusing any version but the pinned one (another
    version can write a different lock from the same inputs)."""
    cmd = [sys.executable, "-m", "uv"]
    try:
        out = subprocess.run(cmd + ["--version"], capture_output=True, text=True,
                             check=True).stdout.split()
    except (OSError, subprocess.CalledProcessError):
        sys.exit("uv is not installed: pip install --require-hashes -r requirements/ci-lock.txt")
    if out[1] != pinned_uv():
        sys.exit(f"uv {out[1]} is installed; tools/lock.py needs uv {pinned_uv()}.")
    return cmd


def compile_lock(uv, source, options, purpose, out_path, cutoff, upgrade=()):
    """Write the lock for `source` to out_path, keeping the versions already
    in out_path (uv reads them as preferences)."""
    extra = [arg for name in upgrade for arg in ("--upgrade-package", name)]
    subprocess.run(uv + ["pip", "compile", source, "-o", str(out_path), "--exclude-newer",
                         cutoff] + options + COMMON + extra, cwd=ROOT, check=True)
    text = Path(out_path).read_text(encoding="utf-8")
    Path(out_path).write_text(header(source, purpose, cutoff) + body(text), encoding="utf-8",
                              newline="\n")


def entries(text):
    """{name: (block lines, names it is a dependency of)} from a lock."""
    found, current = {}, None
    for line in text.replace("\r\n", "\n").split("\n"):
        m = re.match(r"^([A-Za-z0-9][A-Za-z0-9_.-]*)==", line)
        if m:
            current = norm(m.group(1))
            found[current] = ([line], [])
        elif current and line.startswith("    "):
            found[current][0].append(line)
            via = re.match(r"^\s+# via (.*)$", line)
            if via:
                found[current][1].extend(
                    norm(v.strip()) for v in via.group(1).split(",")
                    if v.strip() and not v.strip().startswith("-"))
    return found


def subset(text, names):
    """The hashed lines for `names` and everything they depend on, for
    pip install --require-hashes --no-deps."""
    found = entries(text)
    needs = {}
    for name, (_, parents) in found.items():
        for parent in parents:
            needs.setdefault(parent, set()).add(name)
    wanted, todo = set(), [norm(n) for n in names]
    while todo:
        name = todo.pop()
        if name in wanted:
            continue
        if name not in found:
            sys.exit(f"{name} is not in the lock.")
        wanted.add(name)
        todo += sorted(needs.get(name, ()))
    return "".join("\n".join(found[n][0]) + "\n" for n in found if n in wanted)


def main(argv=None):
    p = argparse.ArgumentParser(description="Generate or check the hash-locked requirements.")
    p.add_argument("--check", action="store_true", help="fail if a lock is out of date")
    p.add_argument("--upgrade-package", action="append", default=[], metavar="NAME")
    p.add_argument("--subset", nargs="+", metavar="NAME",
                   help="these packages and their dependencies from requirements.txt")
    p.add_argument("--output", help="with --subset: write here (UTF-8) instead of printing")
    args = p.parse_args(argv)
    if args.subset:
        text = subset((ROOT / "requirements.txt").read_text(encoding="utf-8"), args.subset)
        if args.output:
            Path(args.output).write_text(text, encoding="utf-8", newline="\n")
        else:
            sys.stdout.write(text)
        return 0
    uv = uv_command()
    today = datetime.date.today()
    stale = []
    for source, target, options, purpose in LOCKS:
        lock = ROOT / target
        if not args.check:
            cutoff = (today - datetime.timedelta(days=COOLDOWN_DAYS)).isoformat()
            compile_lock(uv, source, options, purpose, lock, cutoff, args.upgrade_package)
            print(f"{target}: written")
            continue
        current = lock.read_text(encoding="utf-8").replace("\r\n", "\n") if lock.exists() else ""
        cutoff = recorded_cutoff(current)
        if cutoff is None:
            stale.append(target)
            continue
        with tempfile.TemporaryDirectory() as tmp:
            trial = Path(tmp) / lock.name
            shutil.copyfile(lock, trial)
            compile_lock(uv, source, options, purpose, trial, cutoff)
            fresh = trial.read_text(encoding="utf-8")
        if current != fresh:
            stale.append(target)
    if stale:
        print("Out of date: " + ", ".join(stale) + ". Run python tools/lock.py and commit "
              "the result.")
        return 1
    if args.check:
        print("Every lock matches its .in file.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
